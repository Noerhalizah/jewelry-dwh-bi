--membuat schema staging
CREATE SCHEMA IF NOT EXISTS staging;


--memastikan schema berhasil dibuat

SELECT schema_name
FROM information_schema.schemata
WHERE schema_name = 'staging';

--membuat tabel staging
DO $$
DECLARE
    t RECORD;
BEGIN
    FOR t IN
        SELECT tablename
        FROM pg_tables
        WHERE schemaname = 'public'
    LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS staging.%I
             AS SELECT * FROM public.%I
             WITH NO DATA',
            t.tablename,
            t.tablename
        );
    END LOOP;
END $$;

